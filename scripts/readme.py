"""Generate README.md from built SVG assets."""
from __future__ import annotations

from datetime import date
from html import escape

from board import board_label
from cards import hero_label, whoami_label
from graphs import graph_titles


def picture(name: str, width: str, alt: str) -> str:
    # dark + light sources for GitHub theme preference
    dark = f"assets/{name}-dark.svg"
    light = f"assets/{name}-light.svg"
    return (
        f'<picture>\n'
        f'  <source media="(prefers-color-scheme: dark)" srcset="{dark}">\n'
        f'  <img src="{light}" alt="{escape(alt)}" width="{width}">\n'
        f"</picture>"
    )


def link(url: str, inner: str) -> str:
    return f'<a href="{escape(url)}">{inner}</a>'


def render(data: dict, P: dict) -> str:
    L = P["links"]
    today = date.fromisoformat(data["today"])
    out: list[str] = []

    out += [
        "<!-- HAFIZ ALI SALMAN — generated by scripts/build.py; do not edit by hand -->",
        link(L["github"]["url"], picture("hero", "100%", hero_label(P, data))),
        "",
    ]

    badges = []
    for key, file in (("github", "badge-gh"), ("linkedin", "badge-li"), ("email", "badge-email")):
        alt = f"{L[key]['label']} {L[key].get('handle', '')}".strip()
        badges.append(link(L[key]["url"], picture(file, "220", alt)))
    out += ['<p align="center">', " ".join(badges), "</p>", ""]

    out += [picture("github", "100%", board_label(data)), ""]

    for key, summary, total, title in graph_titles(data, today):
        unit = "contribution" if total == 1 else "contributions"
        out += [
            f'<p align="center"><b>{escape(summary)}</b>: {total:,} {unit}</p>',
            "",
            picture(f"graph-{key}", "100%", title),
            "",
            "<br/>",
            "",
        ]

    out += [picture("whoami", "100%", whoami_label(data, P)), ""]
    out += [picture("label-ship", "100%", "What I ship"), ""]

    apps = []
    for a in P["apps"]:
        apps.append(link(a["url"], picture(f"app-{a['id']}", "49%", a["name"])))
    # pair into rows of 2
    out.append('<p align="center">')
    for i in range(0, len(apps), 2):
        chunk = apps[i : i + 2]
        out.append(" ".join(chunk))
        if i + 2 < len(apps):
            out.append("<br/>")
    out += ["</p>", ""]

    more = " · ".join(link(m["url"], m["name"]) for m in P.get("more", []))
    if more:
        out += [f'<p align="center">More ships: {more}</p>', ""]

    out += [
        '<p align="center">',
        "Drawn in the Hafiz Ali Salman teal design system · numbers redrawn nightly by a GitHub Action · ",
        f'{link(L["linkedin"]["url"], "LinkedIn")} · {link(L["github"]["url"], "GitHub")}',
        "</p>",
        "",
    ]
    return "\n".join(out)
